export const getMandiPrices = (category?: string, searchTerm?: string): MandiRecord[] => {
  return SAMPLE_MANDI_DATA.filter((item) => {
    const matchesCategory = !category || category === 'All' || item.category === category;
    const matchesSearch =
      !searchTerm ||
      item.cropName.toLowerCase().includes(searchTerm.toLowerCase()) ||
      item.cropNameKn.includes(searchTerm) ||
      item.marketName.toLowerCase().includes(searchTerm.toLowerCase()) ||
      item.district.toLowerCase().includes(searchTerm.toLowerCase());
    return matchesCategory && matchesSearch;
  });
};
